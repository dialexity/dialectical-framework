def test_the_population_matches_the_preregistration() -> None:
    """No LLM. Prints the plan and checks the arms are balanced."""
    rows = _population()
    texts = _distinct_texts()
    print("\n=== pre-registered population ===")
    print(f"Set A (replication) : {len(_SET_A)} statements")
    print(f"Set B (form test)   : {len(_FORM_TRIPLETS)} domains x 3 arms = "
          f"{3 * len(_FORM_TRIPLETS)}")
    print(f"rows                : {len(rows)}")
    print(f"distinct texts      : {len(texts)}")
    print(f"readings each       : {_READINGS}")
    print(f"provider calls      : {len(texts) * _READINGS}")
    print(f"\nE1 instability if <= {_PREREG_E1_UNSTABLE_CEILING}/12 unanimous")
    print(f"E2 form effect if gap >= {_PREREG_E2_GAP} AND p < 0.05; "
          f"null if gap <= {_PREREG_E2_NULL_GAP}")

    print("\n=== Set B, by arm ===")
    for arm in _ARMS:
        members = [t for _s, a, t in rows if a == arm]
        print(f"  {arm:<15} n={len(members)}  e.g. {members[0]!r}")

    # Every arm must be the same size, or a unanimity-count comparison between
    # arms is comparing different denominators.
    sizes = {arm: len([1 for _s, a, _t in rows if a == arm]) for arm in _ARMS}
    assert len(set(sizes.values())) == 1, sizes
    assert sizes["LONG_CONCRETE"] == len(_FORM_TRIPLETS)
    # Set A must stay verbatim-comparable to probe_tetrad_pole's three readings.
    assert len(_SET_A) == 12
    # The form arms must actually differ in form, or E2 measures nothing.
    for domain, short_abstract, short_concrete, long_concrete in _FORM_TRIPLETS:
        assert len(short_abstract.split()) == 1, domain
        assert 3 <= len(short_concrete.split()) <= 4, domain
        assert 9 <= len(long_concrete.split()) <= 14, domain


