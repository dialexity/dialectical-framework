"""Does `StatementClassification` return the same answer twice for the same text?

WHY THIS EXISTS
===============
`probe_tetrad_pole.py` measured a prompt fix by comparing two runs it declared
matched — "held fixed: population, tier, auditor, audit prompt; only the
generation prompt moves". That was false, and the probe's own readout is what
exposed it. The classification of the 12 poles differed between runs, and the
branch it returns is not metadata: `lookup_aspect_apex(parent, position)` uses it
to select the apex row interpolated into `_tetrad_prompt`. Four of twelve poles
therefore taught the generator from a different apex on the second run.

Three readings of those 12 poles (baseline / run 1 / run 2) gave:

  Buy the cofounder out now       Integrity   Integrity   Integrity    stable
  Retain the cofounder            Integrity   Integrity   Integrity    stable
  Take full ownership solo        Integrity   Integrity   Integrity    stable
  Collective                      Integrity   Integrity   Integrity    stable
  Mandate uniform process         Integrity   Integrity   Integrity    stable
  Let teams own their process     Flexibility Flexibility Flexibility  stable
  Individual                      SIMPLE      SIMPLE      SIMPLE       stable
  Secure the anchor accounts      Integrity   Resilience  Integrity    wobbles
  Security                        Integrity   Integrity   Resilience   wobbles
  Wait until unknowns resolve     Fidelity    Integrity   Fidelity     wobbles
  Decide now and commit           Flexibility Fire        Fire         CROSSES
  Freedom                         Water       Air         Fire         3 for 3

Two claims came out of that, and they have very different evidential standing.
The first — that classification is unstable — is a direct reading of the data.
The second — that the split is by FORM, long concrete course-of-action stable and
short abstract noun not — is a hypothesis GENERATED by staring at those 12 rows.
Testing it on those same 12 rows would be circular, which is why Set B below is
new text written for the purpose.

This matters beyond the probe. Per CLAUDE.md the branch also feeds HS, which
gates `_rank_polarities` at `HS_THRESHOLD=0.7`; and the SIMPLE/COMPLEX boundary
is "the most leverage-dense prompt in the extraction pipeline", because SIMPLE
hardcodes HS to 1.0 and inflates every polarity past that gate.

PRE-REGISTRATION (written before any statement was classified, 2026-08-20)
=========================================================================
Population: 48 statements x 6 readings = 288 classifications, all on the WEAK
tier — the tier that produced the observation and that the archive ran on. A
stable result on a stronger model would not retire this.

  SET A  (12, replication)  The exact 12 poles `probe_tetrad_pole.py` classified,
                            verbatim, so the 3-reading observation gets a 6-reading
                            test on the same text.
  SET B  (36, form test)    12 domains x 3 arms, matched by domain so domain is not
                            the confound:
                              SHORT_ABSTRACT  a bare noun ("Autonomy")
                              SHORT_CONCRETE  a 3-4 word action ("Delay the launch")
                              LONG_CONCRETE   a 9-14 word course of action

Primary endpoint: BRANCH UNANIMITY — a statement is unanimous iff all 6 readings
return the same branch. Chosen over "modal agreement rate" because the downstream
consumer takes ONE reading: a statement that is right 4 times in 6 still teaches
the generator a different apex whenever it is not.

E1, Set A replication — unanimous count out of 12:
  * CONFIRMS INSTABILITY  <= 8/12
  * CONTRADICTS IT        12/12. The 3-reading drift was an unlucky sample and
                          this whole line of inquiry was noise.
  * PARTIAL               9..11/12.

E2, Set B form hypothesis (the new claim), 12 per arm:
  * FORM EFFECT REAL   LONG_CONCRETE unanimous - SHORT_ABSTRACT unanimous >= 6
                       AND Fisher two-sided p < 0.05. Both, because at 12 per arm
                       a gap of 6 is roughly what p<0.05 needs, and a bare count
                       would over-read a smaller one.
  * NO FORM EFFECT     gap <= 2.
  * INDETERMINATE      3..5.
  SHORT_CONCRETE is the discriminator and is reported, not gated: if it tracks
  LONG_CONCRETE then CONCRETENESS drives stability; if it tracks SHORT_ABSTRACT
  then LENGTH does. Two arms could not have told those apart.

Severity secondaries, reported separately because each has a different downstream
consequence and a different fix:
  * SIMPLE/COMPLEX FLIP — highest severity, independent of any branch count. One
    flip forces HS to 1.0 on some readings and not others, which moves the polarity
    across `HS_THRESHOLD=0.7`. A statement that flips is a defect even if its
    COMPLEX readings are unanimous on branch.
  * TAXONOMY CROSS (`System(` <-> `Elements(`) — swaps the apex vocabulary
    wholesale rather than picking a neighbouring row.
  * DOMAIN DRIFT (General / Engineering / Ecology / Institutions / Love) — the
    domain is also an argument to the apex lookup, so it changes the taught apex
    even when the branch holds. Deliberately NOT folded into branch unanimity, so
    that a stable-branch / drifting-domain statement cannot be scored as clean.

Pre-declared confound: the three arms bundle length, concreteness, and
naming-an-action. Three arms separate length from concreteness; nothing here
isolates "names an action". Any positive result is about FORM as a bundle and the
write-up must say so rather than claiming abstractness specifically.

Pre-declared non-confound: no graph is touched and no generation runs, so there
is no ordering, no scope, and no shared cache. Each reading constructs a fresh
`StatementClassification`. The only variance is the provider's.

RESULT (2026-08-20, 288 classifications over 47 unique texts, weak tier)
=======================================================================
"Security" appears in both sets verbatim, so 48 rows resolve to 47 texts.

E1, Set A replication: 6/12 branch-unanimous. INSTABILITY CONFIRMED — the bar
was <= 8/12 and it cleared with margin. The 3-reading table above understated
it: 7 of those 12 looked stable across 3 readings, 6 survive 6. Nothing here
was an unlucky sample.

E2, the form hypothesis: REFUTED on the registered endpoint.

  SHORT_ABSTRACT   6/12 unanimous
  SHORT_CONCRETE   5/12
  LONG_CONCRETE    7/12
  gap = 1 (needed >= 6), Fisher two-sided p = 1.0000 (needed < 0.05)

Both prongs missed, and gap <= 2 is the pre-registered NO FORM EFFECT band, so
this is a positive null and not an underpowered miss: 12 fresh long concrete
courses of action are no more stably classified than 12 bare nouns. The Set A
pattern that generated this hypothesis was me reading form onto 12 rows that
happened to line up. It does not reproduce on text written to test it, which is
exactly what the non-circular Set B was for. The SHORT_CONCRETE discriminator is
therefore uninterpretable by construction and the readout now says so instead of
naming a winner.

Severity secondaries:

  * SIMPLE/COMPLEX FLIP: 0 of 47. The highest-severity mode does not occur. The
    boundary CLAUDE.md calls "the most leverage-dense prompt in the extraction
    pipeline" is the one thing here that is solid — no statement was SIMPLE on
    one reading and COMPLEX on another, so nothing silently forced HS to 1.0.
    This is the load-bearing reassurance in the whole run.

  * TAXONOMY CROSS: 5 of 47 — Freedom (Water/Flexibility), Decide now and commit
    (Flexibility/Fire), Speed (Fire/Exchange), Growth (Flexibility/Fire),
    Caution (Water/Resilience). All five are short: four bare nouns and one
    4-word phrase. By arm within Set B: SHORT_ABSTRACT 3/12, SHORT_CONCRETE
    0/12, LONG_CONCRETE 0/12.

  * DOMAIN DRIFT: 12 of 47, spread across all three arms (Freedom and Autonomy
    and Transparency General/Institutions, Security Engineering/General,
    Pair-program every feature Engineering/Institutions, ...). This is why it
    was kept out of branch unanimity: folding branch and domain together, only
    18 of 47 texts (38%) return the SAME (family, domain, branch) on all six
    readings. Per arm, any-instability: Set A 8/12, SHORT_ABSTRACT 8/12,
    SHORT_CONCRETE 8/12, LONG_CONCRETE 6/12 (Set A vs LONG_CONCRETE p = 0.68).
    The taught apex is less stable than the primary endpoint alone suggests.

A hypothesis GENERATED HERE, banked as untested, not as a finding
----------------------------------------------------------------
Form failed on how OFTEN a statement is unstable, but every taxonomy cross in
the run is a short statement. Pooling the two comparison arms gives 3/12 vs 0/24,
p = 0.0308 — and that number must not be reported as a result. The pooling was
chosen after seeing which grouping reached significance; the unpooled comparison
that was equally available (SHORT_ABSTRACT 3/12 vs SHORT_CONCRETE 0/12) is
p = 0.2174; no threshold was pre-registered on this channel; and it is one of
several secondary comparisons on one dataset. It is the same "stare at the rows
until a pattern appears" move that produced the hypothesis this run just killed,
so it gets the same treatment: written down, owed a pre-registered test on new
text before anyone acts on it. If it survives one, the readable mechanism is
that a bare noun gives the classifier nothing to anchor a family on, so it
crosses System/Elements rather than picking a neighbouring branch — a severity
effect, not a frequency one.

What this run does and does not license
--------------------------------------
Licensed: `probe_tetrad_pole.py`'s "held fixed, only the generation prompt moves"
was wrong, and quantifiably so — half its population changes branch across
readings and 62% changes the taught apex. Any future measurement downstream of
this classifier must either pin the classification or report it as a confound.
NOT licensed: any claim about which statements are unstable, or any prompt edit
to `statement_classification.py` justified by form. The cause is unidentified.

Run:
  poetry run pytest tests/e2e/probe_classifier_stability.py -s --real-llm
  poetry run pytest tests/e2e/probe_classifier_stability.py -s   (free: prints the
      population and the arm balance, no provider calls)
"""

