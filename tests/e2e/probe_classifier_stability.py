# Pre-registered decision thresholds, named so the readout cannot quietly use
# different numbers than the docstring.
_PREREG_E1_UNSTABLE_CEILING = 8      # <= this many unanimous of 12 => instability
_PREREG_E2_GAP = 6                   # LONG_CONCRETE - SHORT_ABSTRACT unanimity
_PREREG_E2_NULL_GAP = 2              # <= this => no form effect


def _population() -> list[tuple[str, str, str]]:
    """(set_name, arm, text) for every statement, deduplicated within a set.

    Set A and Set B overlap on nothing by construction — Set A's short nouns are
    Freedom/Security/Individual/Collective and Set B's are different words — but
    "Security" appears in BOTH, and deliberately: it is the one statement that
    gets a 6-reading result usable in E1 and E2 at once. It is counted once in
    each set's tally and classified once, so the readings are shared, not doubled.
    """
    rows: list[tuple[str, str, str]] = [("A", "SET_A", text) for text in _SET_A]
    for _domain, short_abstract, short_concrete, long_concrete in _FORM_TRIPLETS:
        rows.append(("B", "SHORT_ABSTRACT", short_abstract))
        rows.append(("B", "SHORT_CONCRETE", short_concrete))
        rows.append(("B", "LONG_CONCRETE", long_concrete))
    return rows


def _distinct_texts() -> list[str]:
    """Every text needing readings, once. Preserves first-seen order."""
    seen: dict[str, None] = {}
    for _set_name, _arm, text in _population():
        seen.setdefault(text, None)
    return list(seen)


def _family_of(meaning: str) -> str:
    if meaning.startswith(SYSTEMIC_PREFIX):
        return "System"
    if meaning.startswith(ELEMENTAL_PREFIX):
        return "Elements"
    return "Simple" if "Simple" in meaning else "?"


def _reading_key(result: ClassificationResult) -> tuple[str, str, str, str]:
    """(simple, family, domain, branch) — everything that changes the taught apex.

    `leaf` is excluded on purpose: `lookup_aspect_apex` keys on branch (+domain),
    so a differing leaf does not change what the generator is taught and folding
    it in would inflate the instability count.
    """
    if result.is_simple:
        return ("SIMPLE", "Simple", "-", "-")
    domain, _category, branch, _leaf = parse_meaning_uri(result.meaning)
    return (
        "COMPLEX",
        _family_of(result.meaning),
        domain or "?",
        branch or "?",
    )


def _fisher_exact_two_sided(a: int, b: int, c: int, d: int) -> float:
    """p-value for [[a,b],[c,d]], no SciPy. Same convention as the other probes."""
    from math import comb

    n = a + b + c + d
    row1, col1 = a + b, a + c

    def prob(x: int) -> float:
        return comb(row1, x) * comb(n - row1, col1 - x) / comb(n, col1)

    lo = max(0, col1 - (n - row1))
    hi = min(row1, col1)
    observed = prob(a)
    return min(1.0, sum(p for x in range(lo, hi + 1)
                        if (p := prob(x)) <= observed + 1e-9))


