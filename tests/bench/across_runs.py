"""Pool an effect across every saved run, and see whether it was ever real.

    poetry run python tests/bench/across_runs.py

The bench's unit of publication is a RUN, and a run is 3 replicates. `report.py`
now prints an honest interval inside each one, which is what stopped false
positives being announced — but it cannot catch the other error, the one that
takes a whole archive to see: an effect that is significant-looking in the run
you happen to be reading and absent when the previous fifteen are stacked
against it. Every run in `results/` was generated by a slightly different build,
so this is not a clean meta-analysis; it is the crudest available check on
whether a number is a property of the ARM or a property of that afternoon.

Two effects are pooled, both of which were quoted as findings from r16 alone:

  * **durability** — the composite's opening-vs-return change (`report.py`'s
    "under pressure" block). r16: -1.22.
  * **closure** — the question-ending rate change (`scoring.score_closure`).
    r16: A1.7 -0.03 against A2 +0.31.

Neither survives pooling. That is the point of the script, and the reason it is
committed rather than run once: the next time a single run produces a striking
split, this is the two-minute check that comes before the write-up.

A MEASUREMENT script, not a test: it prints and exits 0. Free — no LLM, no DB,
pure functions over saved transcripts.
"""

from __future__ import annotations

import math
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
RESULTS = BENCH_DIR / "results"
sys.path.insert(0, str(BENCH_DIR.parent))

from bench.models import Comparison, RunRecord  # noqa: E402
from bench.report import _ci95, _fmt_ci, collect_deltas, load_records  # noqa: E402
from bench.runner import score_machine_over  # noqa: E402

#: Prompt arms in descending strength. The comparison that matters is A2 against
#: the STRONGEST prompt arm a run happened to include — beating A0 proves nothing
#: the ablation ladder does not already concede.
_PROMPT_ARMS = ("A1.7", "A1.5", "A1", "A0")


def _stems() -> list[str]:
    """Saved runs worth pooling.

    `-runs` is the same payload under a second name, `-rejudged` is the same cells
    scored twice (pooling it would count one run as two), and `smoke*` are harness
    checks with 1-2 cells. Including any of them inflates n with no new evidence.
    """
    return sorted(
        p.stem
        for p in RESULTS.glob("*.json")
        if not p.stem.endswith(("-runs", "-rejudged"))
        and not p.stem.startswith("smoke")
    )


def sign_test(values: list[float]) -> float:
    """Two-sided sign test p-value for "the median is zero".

    Used alongside the mean's CI because it assumes almost nothing: the runs come
    from different builds with different variances, so a t-interval over them is
    already generous. When the CI and the sign test disagree, believe the sign
    test.
    """
    nonzero = [v for v in values if v != 0]
    n = len(nonzero)
    if not n:
        return 1.0
    k = sum(1 for v in nonzero if v > 0)
    k = max(k, n - k)
    tail = sum(math.comb(n, i) for i in range(k, n + 1)) / 2**n
    return min(1.0, 2 * tail)


def durability_rows() -> list[tuple[str, str, str, float, int]]:
    """(stem, arm pair, tier, mean composite change, replicates) per saved set."""
    rows: list[tuple[str, str, str, float, int]] = []
    for stem in _stems():
        payload = load_records(RESULTS / f"{stem}.json")
        comparisons = [
            Comparison.model_validate(c) for c in payload.get("comparisons") or []
        ]
        if not comparisons:
            continue
        for (arm_a, arm_b), deltas in collect_deltas(comparisons).items():
            for tier in sorted({c.tier for c in comparisons}):
                changes = deltas.pressure_changes(tier)
                if len(changes) < 2:
                    continue
                rows.append(
                    (
                        stem,
                        f"{arm_a.value} v {arm_b.value}",
                        tier,
                        st.mean(changes),
                        len(changes),
                    )
                )
    return rows


def closure_rows() -> list[tuple[str, str, float, float, int]]:
    """(stem, prompt arm, its mean change, A2's mean change, cells) per run.

    Machine scores are RE-COMPUTED from the transcripts rather than read from the
    saved `machine` block: `closure` postdates every run in the archive, and the
    whole reason a machine scorer is worth having is that it applies backwards for
    free.
    """
    rows: list[tuple[str, str, float, float, int]] = []
    for stem in _stems():
        payload = load_records(RESULTS / f"{stem}.json")
        runs = [RunRecord.model_validate(r) for r in payload["runs"]]
        machine = score_machine_over(runs, {})
        per_arm: dict[str, list[float]] = defaultdict(list)
        for key, scores in machine.items():
            change = scores.closure.rate_change if scores.closure else None
            if change is not None:
                per_arm[key.split("|")[0]].append(change)
        if "A2" not in per_arm:
            continue
        base = next((a for a in _PROMPT_ARMS if a in per_arm), None)
        if base is None:
            continue
        rows.append(
            (stem, base, st.mean(per_arm[base]), st.mean(per_arm["A2"]), len(per_arm["A2"]))
        )
    return rows


def _summarise(label: str, values: list[float], expect: str) -> None:
    if len(values) < 2:
        print(f"  {label}: too few sets to pool ({len(values)})")
        return
    positive = sum(1 for v in values if v > 0)
    print()
    print(
        f"  {label}: n={len(values)} sets  mean {st.mean(values):+.3f}  "
        f"sd {st.stdev(values):.3f}  {_fmt_ci(_ci95(values))}"
    )
    print(
        f"  {'':{len(label)}}  positive in {positive}/{len(values)}  "
        f"sign test p={sign_test(values):.3f}"
    )
    print(f"  -> {expect}")


def main() -> int:
    print("=" * 74)
    print("DURABILITY — composite change from the opening to the returning session")
    print("=" * 74)
    rows = durability_rows()
    for stem, pair, tier, change, n in rows:
        print(f"  {stem:34} {pair:12} {tier:7} {change:+.2f}  (reps {n})")
    _summarise(
        "durability",
        [r[3] for r in rows],
        "r16's -1.22 does not replicate: it is the archive's most extreme value "
        "in either\n     direction, and the pooled effect is indistinguishable "
        "from zero. The split is a\n     useful DECOMPOSITION; it was not a "
        "finding.",
    )

    print()
    print("=" * 74)
    print("CLOSURE — change in the share of turns ending on a question")
    print("=" * 74)
    crows = closure_rows()
    for stem, base, base_v, a2_v, n in crows:
        print(
            f"  {stem:34} {base:5} {base_v:+.2f} -> A2 {a2_v:+.2f}   "
            f"diff {a2_v - base_v:+.2f}  (cells {n})"
        )
    _summarise(
        "closure",
        [a2 - b for _s, _b, b, a2, _n in crows],
        "A2 does drift toward asking rather than advising on return, but so does "
        "the prompt\n     arm: the DIFFERENCE is small and does not resolve. r16's "
        "+0.31-vs--0.03 was one\n     draw. Do not prompt-fix an arm difference "
        "this has not established.",
    )

    print()
    print(
        "Standing caveat: every run here was produced by a different build, so\n"
        "this pools apples and pears on purpose. It is strong evidence AGAINST an\n"
        "effect (a real arm property should survive its own codebase changing) and\n"
        "weak evidence for one."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
